test_that("readd, loadd and outdated work like drake's", {
  open_mini()
  expect_setequal(outdated(), all_chunks)
  a <- readd(L100.base)
  expect_named(a, "L100.base")
  expect_identical(a[[1]], get_minaj("L100.base"))
  expect_identical(readd("mini/A100.base"), readd("mini.A100.base", character_only = TRUE))
  e <- new.env()
  expect_identical(loadd(L100.base, list = "mini/A200.coef", envir = e), c("L100.base", "mini.A200.coef"))
  expect_setequal(ls(e), c("L100.base", "mini.A200.coef"))
  expect_identical(e$L100.base, a)
  expect_setequal(outdated(), setdiff(all_chunks, "module_mini_L100.base"))
  expect_error(readd("L999.none", character_only = TRUE), "not a data object, CSV input or XML file")
})

test_that("driver_minaj with stop_after, stop_before and return_data_names, like driver_drake", {
  open_mini()
  r <- suppressMessages(driver_minaj(stop_after = "mini_L200.coef", write_xml = FALSE))
  expect_named(r, c("L200.Subsector", "L200.SubsectorShrwtFllt", "L200.StubTechCoef"))
  expect_identical(r$L200.StubTechCoef, get_minaj("L200.StubTechCoef"))
  r2 <- suppressMessages(driver_minaj(stop_before = "module_mini_mini_xml", write_xml = FALSE, return_data_names = "L201.Subsector"))
  expect_setequal(names(r2), c("L201.Subsector", "L200.Subsector", "L200.SubsectorShrwtFllt", "L200.StubTechCoef"))
  expect_setequal(outdated(), c("module_mini_mini_xml", "module_mini_other_xml"))
  expect_length(suppressMessages(driver_minaj(write_xml = FALSE)), 0)
  expect_length(outdated(), 0)
  expect_false(file.exists(file.path(info_minaj()$dest, "mini.xml")))
  expect_error(driver_minaj(user_modifications = "x"), "use variants_minaj")
  expect_warning(suppressMessages(driver_minaj(stop_after = "mini_L100.base", write_xml = FALSE, return_plan_only = TRUE)), "not supported, ignored: return_plan_only")
})
